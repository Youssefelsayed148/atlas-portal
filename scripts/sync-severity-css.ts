import fs from "fs";
import path from "path";
import { severityTokens } from "../app/lib/severity-tokens";

/**
 * Generates app/severity-vars.css from app/lib/severity-tokens.ts — the single
 * source of truth for the severity hex scale. Runs automatically via the
 * predev/prebuild/prestart package.json hooks (or manually: pnpm severity:sync).
 */
function block(selector: string): string {
  const lines = Object.entries(severityTokens)
    .map(([key, hex]) => `  --${key}: ${hex};`)
    .join("\n");
  return `${selector} {\n${lines}\n}`;
}

const css = `/* AUTO-GENERATED by scripts/sync-severity-css.ts — do not edit by hand.
   Source of truth: app/lib/severity-tokens.ts (also read by components/severity.tsx).
   Regenerate with: pnpm severity:sync (runs automatically before dev/build/start). */
${block(":root")}

${block(".dark")}
`;

const out = path.resolve(__dirname, "..", "app", "severity-vars.css");
fs.writeFileSync(out, css);
console.log(`Wrote ${out}`);